#!/usr/bin/env python3

import argparse
from pathlib import Path

from PIL import ImageFont


FIRST_CHARACTER = 0x20
LAST_CHARACTER = 0x7E
GLYPH_SIZE = 8


def parse_arguments():
    parser = argparse.ArgumentParser(
        description="Generate an 8x8 BigLetters font pack from a pixel TTF."
    )
    parser.add_argument("font", type=Path)
    parser.add_argument("--symbol", required=True)
    parser.add_argument("--name", required=True)
    parser.add_argument("--description", required=True)
    return parser.parse_args()


def rasterize(font, character):
    mask, offset = font.getmask2(character, mode="1")
    rows = [0] * GLYPH_SIZE

    if round(font.getlength(character)) != GLYPH_SIZE:
        raise ValueError(f"{character!r} does not have an 8-pixel advance")

    pixels = list(mask)
    for source_y in range(mask.size[1]):
        target_y = offset[1] + source_y
        if target_y < 0 or target_y >= GLYPH_SIZE:
            raise ValueError(f"{character!r} extends outside the 8x8 cell")

        for source_x in range(mask.size[0]):
            target_x = offset[0] + source_x
            if target_x < 0 or target_x >= GLYPH_SIZE:
                raise ValueError(f"{character!r} extends outside the 8x8 cell")
            if pixels[source_y * mask.size[0] + source_x]:
                rows[target_y] |= 1 << (7 - target_x)

    return rows


def character_label(character):
    labels = {
        " ": "space",
        "\\": "backslash",
        "'": "apostrophe"
    }
    return labels.get(character, character)


def main():
    arguments = parse_arguments()
    font = ImageFont.truetype(str(arguments.font), GLYPH_SIZE)
    family, style = font.getname()

    print("/*")
    print(f" * Derived from {family} ({style}) by VileR.")
    print(" * Font data license: CC BY-SA 4.0. See FONT-LICENSE.md.")
    print(" * Generated by tools/generate_font_pack.py; do not edit by hand.")
    print(" */")
    print()
    print('#include "bigletters.h"')
    print()
    print(f"static const BiglettersGlyph {arguments.symbol}_glyphs[95] = {{")

    for codepoint in range(FIRST_CHARACTER, LAST_CHARACTER + 1):
        character = chr(codepoint)
        rows = rasterize(font, character)
        row_values = ", ".join(f"0x{row:02x}" for row in rows)
        comma = "," if codepoint < LAST_CHARACTER else ""
        print(
            f"    {{{{{row_values}}}}}{comma} "
            f"/* 0x{codepoint:02x} {character_label(character)} */"
        )

    print("};")
    print()
    print(f"const BiglettersFontPack {arguments.symbol} = {{")
    print(f'    "{arguments.name}",')
    print(f'    "{arguments.description}",')
    print(f"    {arguments.symbol}_glyphs,")
    print(f"    &{arguments.symbol}_glyphs['?' - ' '],")
    print('    "VileR, The Ultimate Oldschool PC Font Pack",')
    print('    "CC BY-SA 4.0"')
    print("};")


if __name__ == "__main__":
    main()
